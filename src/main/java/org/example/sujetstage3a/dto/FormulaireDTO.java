    private Integer id;
    private String titre;
    private String description;

    public FormulaireDTO(Integer id, String titre, String description) {
        this.id = id;
        this.titre = titre;
        this.description = description;
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

